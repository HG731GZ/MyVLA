#!/bin/bash
# =============================================================================
# SimVLA LIBERO Evaluation Script (parallel 4 task suites)
# =============================================================================

set -e

# =============================================================================
# LIBERO Environment Setup
# =============================================================================
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PYTHON_BIN="${PYTHON_BIN:-python}"
LIBERO_ARGS=()

if [ -n "${LIBERO_ROOT:-}" ]; then
    export LIBERO_ROOT
    export PYTHONPATH="${LIBERO_ROOT}${PYTHONPATH:+:${PYTHONPATH}}"
    LIBERO_ARGS=(--libero_root "$LIBERO_ROOT")
fi

export NUMBA_CACHE_DIR="${NUMBA_CACHE_DIR:-${TMPDIR:-/tmp}/simvla_libero_numba}"

echo "LIBERO Environment:"
echo "   LIBERO_ROOT: ${LIBERO_ROOT:-auto-detect from installed package/PYTHONPATH}"
echo "   LIBERO_CONFIG_PATH: ${LIBERO_CONFIG_PATH:-auto-generated by libero_client.py}"
echo "   Python: $PYTHON_BIN"
echo ""

# Default arguments
PORT=${1:-8089}
NUM_TRIALS=${2:-10}
OUTPUT_PREFIX=${3:-"eval_simvla"}
GPUS=${4:-"4 5 6 7"}  # Default GPUs: 4 5 6 7

# Parse GPU list
read -ra GPU_ARRAY <<< "$GPUS"
if [ ${#GPU_ARRAY[@]} -lt 4 ]; then
    echo "ERROR: Need at least 4 GPUs, got ${#GPU_ARRAY[@]}"
    echo "   Usage: $0 <port> <num_trials> <output_prefix> \"<gpu1> <gpu2> <gpu3> <gpu4>\""
    exit 1
fi

GPU_SPATIAL=${GPU_ARRAY[0]}
GPU_OBJECT=${GPU_ARRAY[1]}
GPU_GOAL=${GPU_ARRAY[2]}
GPU_10=${GPU_ARRAY[3]}

# Output directory
OUTPUT_DIR="./eval_simvla_${PORT}"
rm -rf "$OUTPUT_DIR"
mkdir -p "$OUTPUT_DIR"

echo "Starting LIBERO evaluation..."
echo "   Server Port: $PORT"
echo "   Num Trials: $NUM_TRIALS"
echo "   Output Prefix: $OUTPUT_PREFIX"
echo "   Output Dir: $OUTPUT_DIR"
echo "   GPUs: spatial=$GPU_SPATIAL, object=$GPU_OBJECT, goal=$GPU_GOAL, 10=$GPU_10"
echo ""


# Run 4 task suites in parallel
echo "Launching 4 evaluation tasks..."

CUDA_VISIBLE_DEVICES=$GPU_SPATIAL "$PYTHON_BIN" -u "$SCRIPT_DIR/libero_client.py" \
    "${LIBERO_ARGS[@]}" \
    --host 127.0.0.1 \
    --port "$PORT" \
    --client_type websocket \
    --task_suite libero_spatial \
    --num_trials "$NUM_TRIALS" \
    --video_out "$OUTPUT_DIR" > "${OUTPUT_PREFIX}_spatial.txt" 2>&1 &
PID_SPATIAL=$!
echo "   [PID $PID_SPATIAL] libero_spatial (GPU $GPU_SPATIAL) -> ${OUTPUT_PREFIX}_spatial.txt"

CUDA_VISIBLE_DEVICES=$GPU_OBJECT "$PYTHON_BIN" -u "$SCRIPT_DIR/libero_client.py" \
    "${LIBERO_ARGS[@]}" \
    --host 127.0.0.1 \
    --port "$PORT" \
    --client_type websocket \
    --task_suite libero_object \
    --num_trials "$NUM_TRIALS" \
    --video_out "$OUTPUT_DIR" > "${OUTPUT_PREFIX}_object.txt" 2>&1 &
PID_OBJECT=$!
echo "   [PID $PID_OBJECT] libero_object (GPU $GPU_OBJECT) -> ${OUTPUT_PREFIX}_object.txt"

CUDA_VISIBLE_DEVICES=$GPU_GOAL "$PYTHON_BIN" -u "$SCRIPT_DIR/libero_client.py" \
    "${LIBERO_ARGS[@]}" \
    --host 127.0.0.1 \
    --port "$PORT" \
    --client_type websocket \
    --task_suite libero_goal \
    --num_trials "$NUM_TRIALS" \
    --video_out "$OUTPUT_DIR" > "${OUTPUT_PREFIX}_goal.txt" 2>&1 &
PID_GOAL=$!
echo "   [PID $PID_GOAL] libero_goal (GPU $GPU_GOAL) -> ${OUTPUT_PREFIX}_goal.txt"

CUDA_VISIBLE_DEVICES=$GPU_10 "$PYTHON_BIN" -u "$SCRIPT_DIR/libero_client.py" \
    "${LIBERO_ARGS[@]}" \
    --host 127.0.0.1 \
    --port "$PORT" \
    --client_type websocket \
    --task_suite libero_10 \
    --num_trials "$NUM_TRIALS" \
    --video_out "$OUTPUT_DIR" > "${OUTPUT_PREFIX}_10.txt" 2>&1 &
PID_10=$!
echo "   [PID $PID_10] libero_10 (GPU $GPU_10) -> ${OUTPUT_PREFIX}_10.txt"

echo ""
echo "Waiting for all evaluations to complete..."
echo "   Monitor progress with: tail -f ${OUTPUT_PREFIX}_*.txt"
echo ""

# Wait for all tasks and preserve failures from any suite.
FAILED=0
for pid in "$PID_SPATIAL" "$PID_OBJECT" "$PID_GOAL" "$PID_10"; do
    if ! wait "$pid"; then
        FAILED=1
    fi
done

echo ""
echo "All evaluations completed!"
echo ""
echo "Results summary:"
echo "=========================================="
for suite in spatial object goal 10; do
    file="${OUTPUT_PREFIX}_${suite}.txt"
    if [ -f "$file" ]; then
        echo "--- $suite ---"
        grep -Ei "success rate|average" "$file" 2>/dev/null || echo "  (see $file)"
    fi
done
echo "=========================================="

if [ "$FAILED" -ne 0 ]; then
    echo "One or more evaluation suites failed. Check the log files above."
    exit 1
fi
